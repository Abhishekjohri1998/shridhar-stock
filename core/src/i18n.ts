export const STRINGS: Record<Lang, Record<MsgKey, string>> = { en: EN, kn: KN };

export type T = (key: MsgKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const table = STRINGS[lang];
  return (key, vars) => {
    let s = table[key] ?? EN[key];
    for (const [k, v] of Object.entries(vars ?? {})) s = s.split('{' + k + '}').join(String(v));
    return s;
  };
}

/** A name in the shop's language, falling back to the other one when it is blank. */
export function pickName(en: string, kn: string | undefined, lang: Lang): string {
  return lang === 'kn' ? kn || en : en || kn || '';
}
